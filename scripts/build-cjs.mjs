#!/usr/bin/env node
/*
 * Generate the CommonJS build from the single ESM source of truth.
 * Only three mechanical transforms are used: drop the node:crypto import,
 * strip export keywords, and attach a module.exports map.
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = await readFile(path.join(root, 'src', 'index.mjs'), 'utf8');

const EXPORT_NAMES = [
  'JwtGuardError', 'ERROR_CODES', 'SUPPORTED_ALGORITHMS', 'DANGEROUS_HEADERS',
  'signJwt', 'verifyJwt', 'decodeJwtUnsafe', 'inspectJwtHeader',
  'p1363ToDer', 'derToP1363'
];

let body = source;
body = body.replace(/^import crypto from 'node:crypto';$/m, "const crypto = require('node:crypto');");
body = body.replace(/^export default api;$/m, '');
body = body.replace(/^export const /gm, 'const ');
body = body.replace(/^export class /gm, 'class ');
body = body.replace(/^export function /gm, 'function ');

if (body.includes("import crypto from 'node:crypto'") || /^export /m.test(body)) {
  throw new Error('CJS transform left ESM syntax in the generated build');
}

const output = [
  "'use strict';",
  '',
  '/* Generated by scripts/build-cjs.mjs from src/index.mjs. Do not edit directly. */',
  '',
  body.trim(),
  '',
  'module.exports = {',
  ...EXPORT_NAMES.map((name) => '  ' + name + ','),
  '};',
  '',
  'module.exports.default = module.exports;',
  ''
].join('\n');

await mkdir(path.join(root, 'cjs'), { recursive: true });
await writeFile(path.join(root, 'cjs', 'index.cjs'), output, 'utf8');
process.stdout.write('cjs/index.cjs generated from src/index.mjs\n');
